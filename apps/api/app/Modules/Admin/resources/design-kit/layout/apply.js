/*
 * Lays out a screen of the panel by layout/layout.js: the sidebar's order and names, which pages each screen holds and
 * in what order (its tabs, or the settings' side menu), the tabs inside a screen, and any text renamed.
 *
 * Two places run it:
 *   - the local dashboard (examples/), where a page is a file: settings--general.html;
 *   - the live panel through `node serve.mjs` (http://localhost:5501), where a page is an address:
 *     /merchant/settings/general. There the server redraws parts of the screen after every click (Livewire), so the
 *     layout is laid again after each of them.
 *
 * layout/default.js is the panel as it is now: which screen a page belongs to, and the counts the screens showed.
 * Do not edit this file: edit layout.js. Runs on file:// too (no fetch, plain scripts).
 */
(function () {
  'use strict';

  var live = /^\/merchant(\/|$)/.test(location.pathname);
  var say = function (text, bad) {
    var status = document.querySelector('[data-layout-status]');
    if (status) { status.textContent = text; status.style.color = bad ? '#ffb4a8' : ''; }
  };

  // the page this is, as default.js names it: settings--general
  var pageHere = function () {
    if (live) {
      var path = location.pathname.replace(/^\/merchant\/?/, '').replace(/\/+$/, '');
      return path === '' ? 'overview' : path.replace(/\//g, '--');
    }
    return decodeURIComponent(location.pathname.split('/').pop() || '').replace(/\.html$/, '').split('__')[0];
  };
  var hrefOf = function (page) {
    if (live) { return '/merchant' + (page === 'overview' ? '' : '/' + page.replace(/--/g, '/')); }
    return page + '.html';
  };
  var pageOfHref = function (href) {
    if (!href) { return null; }
    if (live) {
      var path = href.replace(/^https?:\/\/[^/]+/, '').split(/[?#]/)[0];
      if (!/^\/merchant(\/|$)/.test(path)) { return null; }
      path = path.replace(/^\/merchant\/?/, '').replace(/\/+$/, '');
      return path === '' ? 'overview' : path.replace(/\//g, '--');
    }
    return href.replace(/\.html.*$/, '').split('__')[0];
  };

  // the counts the screen shows now (live), over the ones captured; kept from the first look, before any is redrawn
  var counts = null;
  var readCounts = function (D) {
    if (counts) { return counts; }
    counts = {};
    Object.keys(D.badges || {}).forEach(function (k) { counts[k] = D.badges[k]; });
    if (live) {
      document.querySelectorAll('nav.lp-section > a').forEach(function (a) {
        var p = pageOfHref(a.getAttribute('href'));
        var c = a.querySelector('.lp-count');
        if (p) { if (c) { counts[p] = c.textContent.trim(); } else { delete counts[p]; } }
      });
    }
    return counts;
  };

  var tabLabel = function (b) {
    var text = '';
    b.childNodes.forEach(function (n) { if (n.nodeType === 3) { text += n.textContent; } });
    return text.replace(/\(\s*\)/g, '').replace(/[\s(]+$/, '').replace(/^[\s)]+/, '').replace(/\s+/g, ' ').trim();
  };
  var tabId = function (b) {
    return b.getAttribute('data-tab') || b.getAttribute('wire:click') || ('text:' + tabLabel(b));
  };
  var setLabel = function (b, label) {
    var first = null;
    b.childNodes.forEach(function (n) { if (!first && n.nodeType === 3 && n.textContent.trim() !== '') { first = n; } });
    if (!first) { return; }
    var m = first.textContent.match(/^(\s*)([\s\S]*?)(\s*\(?\s*)$/);
    if (first.textContent !== m[1] + label + m[3]) { first.textContent = m[1] + label + m[3]; }
  };
  // a tab keeps its id once renamed, so a second pass still finds it
  var tabKey = function (b) {
    if (!b.hasAttribute('data-layout-tab')) { b.setAttribute('data-layout-tab', tabId(b)); }
    return b.getAttribute('data-layout-tab');
  };

  var apply = function () {
    var D = window.LETS_LAYOUT_DEFAULT;
    var L = window.LETS_LAYOUT;
    if (!D) { say('layout/default.js חסר', true); return; }
    if (!L) { say('layout.js לא נטען: יש בו שגיאת כתיב (פסיק, מירכאה או סוגר). פתחו את ה-Console לפרטים.', true); return; }

    var page = pageHere();
    var screens = L.screens || D.screens;
    var menu = L.menu || D.menu;
    var badges = readCounts(D);

    // the screen this page is in now: the one that lists it, else the one it was in
    var screen = null;
    Object.keys(screens).forEach(function (key) {
      (screens[key].pages || []).forEach(function (p) { if (p.page === page) { screen = key; } });
    });
    screen = screen || D.belongs[page] || null;

    var labelOf = function (key) {
      var m = menu.filter(function (m) { return m.screen === key; })[0];
      return (m && m.label) || key;
    };
    var visible = function (key) {
      return ((screens[key] && screens[key].pages) || []).filter(function (p) { return p.page && !p.hidden; });
    };
    var badgeOf = function (p) { return badges[p.page] || null; };

    // ---- the sidebar
    var ul = document.querySelector('.fi-sidebar-group-items');
    if (ul) {
      var lis = Array.prototype.slice.call(ul.querySelectorAll(':scope > li.fi-sidebar-item'));
      var tpl = lis[0] ? lis[0].cloneNode(true) : null;
      var badgeTpl = ul.querySelector('.fi-sidebar-item-badge-ctn');
      badgeTpl = badgeTpl ? badgeTpl.cloneNode(true) : (window.__letsBadgeTpl || null);
      window.__letsBadgeTpl = badgeTpl;
      if (tpl) {
        var old = tpl.querySelector('.fi-sidebar-item-badge-ctn');
        if (old) { old.remove(); }
        var items = [];
        menu.forEach(function (m) {
          var pages = visible(m.screen);
          if (m.hidden || !pages.length) { return; }
          var li = tpl.cloneNode(true);
          var a = li.querySelector('a');
          var on = m.screen === screen;
          li.classList.toggle('fi-active', on);
          a.setAttribute('href', hrefOf(pages[0].page));
          if (on) { a.setAttribute('aria-current', 'page'); } else { a.removeAttribute('aria-current'); }
          li.querySelector('.fi-sidebar-item-label').textContent = m.label;
          var count = pages.map(badgeOf).filter(Boolean)[0];
          if (count && badgeTpl) {
            var b = badgeTpl.cloneNode(true);
            var t = b.querySelector('.fi-badge-label') || b;
            t.textContent = count;
            li.querySelector('.fi-sidebar-item-label').after(b);
          }
          items.push(li);
        });
        // only when it differs, so a pass after a click does not redraw what is already right
        var html = items.map(function (li) { return li.outerHTML; }).join('');
        if (ul.getAttribute('data-layout-html') !== html) {
          ul.textContent = '';
          items.forEach(function (li) { ul.appendChild(li); });
          ul.setAttribute('data-layout-html', html);
        }
      }
    }

    // ---- the screen's pages: tabs under its heading, or a side menu
    var content = document.querySelector('.fi-page-content');
    if (content) {
      var nav = content.querySelector(':scope > nav.lp-section');
      var pages = screen ? visible(screen) : [];
      if (pages.length > 1) {
        var look = (screens[screen] && screens[screen].look) || (D.screens[screen] && D.screens[screen].look) || 'tabs';
        var side = look === 'side';
        var fresh = document.createElement('nav');
        fresh.className = 'lp-section ' + (side ? 'lp-section-side' : 'lp-section-tabs');
        fresh.setAttribute('data-section', screen);
        fresh.setAttribute('aria-label', labelOf(screen));
        (screens[screen].pages || []).forEach(function (p) {
          if (p.group !== undefined && !p.page) {
            if (side) {
              var g = document.createElement('div');
              g.className = 'lp-side-g';
              g.textContent = p.group;
              fresh.appendChild(g);
            }
            return;
          }
          if (!p.page || p.hidden) { return; }
          var a = document.createElement('a');
          a.href = hrefOf(p.page);
          if (p.page === page) { a.className = 'is-on'; a.setAttribute('aria-current', 'page'); }
          var s = document.createElement('span');
          s.textContent = p.label;
          a.appendChild(s);
          if (badgeOf(p)) {
            var c = document.createElement('span');
            c.className = 'lp-count';
            c.textContent = badgeOf(p);
            a.appendChild(c);
          }
          fresh.appendChild(a);
        });
        if (!nav) {
          var hint = content.querySelector(':scope > .lp-hint');
          if (hint) { hint.after(fresh); } else { content.prepend(fresh); }
        } else if (nav.outerHTML !== fresh.outerHTML) {
          nav.replaceWith(fresh);
        }
      } else if (nav) {
        nav.remove();
      }
    }

    // ---- the tabs inside the screen
    var tabs = (L.tabs || {})[page];
    if (tabs) {
      var found = {};
      document.querySelectorAll('.lp-tabs > button, .lp-tabs > a, .rec-tabs > button, [role=tablist] > button').forEach(function (b) {
        found[tabKey(b)] = found[tabKey(b)] || b;
      });
      tabs.forEach(function (t) {
        var b = found[t.tab];
        if (!b) { return; }
        if (t.label) { setLabel(b, t.label); }
        b.style.display = t.hidden ? 'none' : '';
        if (b.parentNode.lastElementChild !== b) { b.parentNode.appendChild(b); }
      });
    }

    // ---- any other text, renamed
    var texts = L.texts || {};
    var has = function (k) { return Object.prototype.hasOwnProperty.call(texts, k); };
    if (Object.keys(texts).length) {
      var bar = document.querySelector('[data-local-bar], [data-kit-bar]');
      var walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
        acceptNode: function (n) {
          var p = n.parentNode;
          if (!p || (bar && bar.contains(n)) || /^(SCRIPT|STYLE|TEXTAREA)$/.test(p.nodeName)) { return NodeFilter.FILTER_REJECT; }
          return has(n.textContent.trim()) ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_SKIP;
        },
      });
      var nodes = [];
      while (walker.nextNode()) { nodes.push(walker.currentNode); }
      nodes.forEach(function (n) {
        var t = n.textContent;
        n.textContent = t.replace(t.trim(), texts[t.trim()]);
      });
      document.querySelectorAll('[placeholder], [title], [aria-label]').forEach(function (el) {
        ['placeholder', 'title', 'aria-label'].forEach(function (attr) {
          var v = el.getAttribute(attr);
          if (v && has(v.trim())) { el.setAttribute(attr, texts[v.trim()]); }
        });
      });
      var title = document.title.split(' - ')[0].trim();
      if (has(title)) { document.title = document.title.replace(title, texts[title]); }
    }

    say('סדר ושמות: לפי layout.js');
  };

  window.LetsLayoutApply = apply;

  var start = function () {
    apply();
    if (!live) { return; }
    // the server redraws what a click changed: lay it out again once it has
    var hook = function () {
      if (!window.Livewire || window.__letsLayoutHooked) { return; }
      window.__letsLayoutHooked = true;
      window.Livewire.hook('commit', function (c) { c.succeed(function () { setTimeout(apply, 0); }); });
    };
    hook();
    document.addEventListener('livewire:init', hook);
    document.addEventListener('livewire:navigated', function () { counts = null; apply(); });
  };
  if (document.readyState === 'loading') { document.addEventListener('DOMContentLoaded', start); } else { start(); }
})();
